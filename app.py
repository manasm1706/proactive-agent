def load_streaming_metrics():
    """
    Reads the Parquet output generated by Spark Structured Streaming.
    Returns an empty DataFrame if no output is available.
    """

    if not STREAMING_OUTPUT.exists():
        return pd.DataFrame(), "Output folder not found."

    parquet_files = list(STREAMING_OUTPUT.rglob("*.parquet"))

    if not parquet_files:
        return pd.DataFrame(), "No Parquet files found yet."

    try:
        metrics = pd.read_parquet(STREAMING_OUTPUT)

        if metrics.empty:
            return pd.DataFrame(), "The streaming output is currently empty."

        return metrics, "Streaming data loaded successfully."

    except ImportError:
        return (
            pd.DataFrame(),
            "Parquet support is missing. Install pyarrow using: pip install pyarrow"
        )

    except Exception as e:
        return pd.DataFrame(), f"Could not read Spark output: {e}"


def find_column(dataframe, possible_names):
    """Finds a column using a list of possible column names."""

    columns = {str(col).lower(): col for col in dataframe.columns}

    for name in possible_names:
        if name.lower() in columns:
            return columns[name.lower()]

    return None


def display_streaming_analytics():
    """Displays Spark Structured Streaming results in Streamlit."""

    st.markdown("### Kafka + Spark Structured Streaming")

    if st.button("🔄 Refresh streaming results"):
        st.rerun()

    metrics, message = load_streaming_metrics()

    if metrics.empty:
        st.warning(message)
        st.info(
            "Run kaggle_pipeline.py first. Spark must generate Parquet "
            "files in outputs/streaming/monthly_customer_metrics/."
        )
        return

    st.success(message)

    customer_col = find_column(
        metrics,
        ["customer_id"]
    )

    transaction_count_col = find_column(
        metrics,
        ["transaction_count", "total_transactions", "count"]
    )

    amount_col = find_column(
        metrics,
        [
            "total_transaction_amount",
            "transaction_amount",
            "total_amount",
            "amount_sum"
        ]
    )

    window_col = find_column(
        metrics,
        ["window"]
    )

    # Summary metrics
    c1, c2, c3 = st.columns(3)

    c1.metric("Processed records", f"{len(metrics):,}")

    if customer_col:
        c2.metric(
            "Customers processed",
            f"{metrics[customer_col].nunique():,}"
        )
    else:
        c2.metric("Customers processed", "N/A")

    if transaction_count_col:
        total_transactions = pd.to_numeric(
            metrics[transaction_count_col],
            errors="coerce"
        ).fillna(0).sum()

        c3.metric(
            "Total transactions",
            f"{total_transactions:,.0f}"
        )
    else:
        c3.metric("Total transactions", "N/A")

    st.divider()

    # Transaction amount chart
    if amount_col:
        st.markdown("**Processed transaction value**")

        amount_data = metrics.copy()
        amount_data[amount_col] = pd.to_numeric(
            amount_data[amount_col],
            errors="coerce"
        )

        if customer_col:
            chart_data = (
                amount_data.groupby(customer_col)[amount_col]
                .sum()
                .sort_values(ascending=False)
                .head(20)
            )

            st.bar_chart(chart_data)

        else:
            st.bar_chart(amount_data[amount_col])

    # Transaction count chart
    if transaction_count_col:
        st.markdown("**Transaction count by customer**")

        if customer_col:
            count_data = metrics.copy()
            count_data[transaction_count_col] = pd.to_numeric(
                count_data[transaction_count_col],
                errors="coerce"
            )

            chart_data = (
                count_data.groupby(customer_col)[transaction_count_col]
                .sum()
                .sort_values(ascending=False)
                .head(20)
            )

            st.bar_chart(chart_data)

    # Window information
    if window_col:
        st.markdown("**Streaming time window**")
        st.caption(
            "Spark's window column contains the start and end of "
            "the aggregation window."
        )

    st.markdown("**Spark processed records**")
    st.dataframe(metrics, use_container_width=True)

    st.download_button(
        "Download Spark streaming results",
        data=metrics.to_csv(index=False).encode("utf-8"),
        file_name="spark_streaming_metrics.csv",
        mime="text/csv"
    )

    st.caption(
        f"Source: {STREAMING_OUTPUT}"
    )


